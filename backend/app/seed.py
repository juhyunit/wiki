def _ago(days: int, hour: int = 10) -> str:
    d = datetime.now() - timedelta(days=days)
    return d.replace(hour=hour, minute=(days * 7) % 60, second=0, microsecond=0).strftime("%Y-%m-%d %H:%M:%S")


